// Dev-only oracle: generates tests/fixtures/saturdays.tsv from @hebcal/core.
// Usage (from repo root): cd tests/tools && npm install && node gen_fixture.mjs
// (gen_fixture.js is a CommonJS shim that loads this ESM file.)
import {Sedra, HDate} from '@hebcal/core';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const version = JSON.parse(readFileSync(join(here, 'node_modules/@hebcal/core/package.json'), 'utf8')).version;

// hebcal transliterated names -> our indices 1..54
const NAMES = ['Bereshit','Noach','Lech-Lecha','Vayera','Chayei Sara','Toldot','Vayetzei','Vayishlach','Vayeshev','Miketz','Vayigash','Vayechi',
  'Shemot','Vaera','Bo','Beshalach','Yitro','Mishpatim','Terumah','Tetzaveh','Ki Tisa','Vayakhel','Pekudei',
  'Vayikra','Tzav','Shmini','Tazria','Metzora','Achrei Mot','Kedoshim','Emor','Behar','Bechukotai',
  'Bamidbar','Nasso',"Beha'alotcha","Sh'lach",'Korach','Chukat','Balak','Pinchas','Matot','Masei',
  'Devarim','Vaetchanan','Eikev',"Re'eh",'Shoftim','Ki Teitzei','Ki Tavo','Nitzavim','Vayeilech',"Ha'azinu",'Vezot Haberakhah'];
const IDX = new Map(NAMES.map((n, i) => [n, i + 1]));

function cell(r) {
  if (r.chag) return 'H';
  return r.parsha.map((n) => {
    const i = IDX.get(n);
    if (!i) throw new Error('Unknown parsha name: ' + n);
    return i;
  }).join('+');
}
const pad = (n) => String(n).padStart(2, '0');
const lines = [`# Saturdays of Hebrew years 5745-5860 generated by @hebcal/core ${version}. ` +
  'Columns: gregorian(YYYY-MM-DD) hy hm(Nisan=1..Adar(I)=12,AdarII=13,Tishrei=7) hd israel diaspora; ' +
  'parsha cells are indices 1..54 joined by "+", or H for a holiday Shabbat (Sedra.lookup().chag).'];
for (let hy = 5745; hy <= 5860; hy++) {
  const il = new Sedra(hy, true), dia = new Sedra(hy, false);
  let d = new HDate(1, 7, hy).onOrAfter(6);
  const end = new HDate(1, 7, hy + 1).abs();
  while (d.abs() < end) {
    const g = d.greg();
    lines.push([`${g.getFullYear()}-${pad(g.getMonth() + 1)}-${pad(g.getDate())}`, d.getFullYear(), d.getMonth(), d.getDate(),
      cell(il.lookup(d)), cell(dia.lookup(d))].join('\t'));
    d = d.add(7, 'd');
  }
}
writeFileSync(join(here, '../fixtures/saturdays.tsv'), lines.join('\n') + '\n');
console.log(`wrote ${lines.length - 1} rows`);
