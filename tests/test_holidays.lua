local HC = require('Module:HolidayChecker')
local P = require('Module:Parsha')

-- 2022-04-23 = 22 Nisan 5782, Saturday
local il = P.computeParsha(2022, 4, 23, true)
local dia = P.computeParsha(2022, 4, 23, false)
T.eq(il.name, 'אחרי מות', 'Israel 22 Nisan 5782')
T.eq(il.holiday, nil, 'Israel no holiday')
T.ok(dia.holiday ~= nil, 'diaspora holiday')
T.eq(dia.name, 'אחרון של פסח', 'diaspora holiday name')
T.eq(dia.holiday.reading.haftarah, 'ישעיהו י, לב – יב, ו', 'acharon shel pesach haftarah')
-- Shabbat Chol HaMoed Sukkot 5786: 2025-10-11 (19 Tishrei)
local chm = P.computeParsha(2025, 10, 11, true)
T.eq(chm.name, 'שבת חול המועד סוכות', 'chol hamoed sukkot')
T.eq(chm.holiday.reading.torah, 'שמות לג, יב – לד, כו', 'chm torah')
-- Shabbat Chol HaMoed Pesach 5785: 2025-04-19 (21 Nisan = 7th day) -> שביעי של פסח
T.eq(P.computeParsha(2025, 4, 19, true).name, 'שביעי של פסח', '7th Pesach')

-- getHoliday matrix
T.eq(HC.getHoliday(5786, 7, 1).key, 'rosh_hashana_1', 'RH1')
T.eq(HC.getHoliday(5786, 7, 16, true).key, 'sukkot_chol_hamoed', 'Sukkot 2 Israel')
T.eq(HC.getHoliday(5786, 7, 16, false).key, 'sukkot_2', 'Sukkot 2 diaspora')
T.eq(HC.getHoliday(5786, 7, 22, true).key, 'simchat_torah', '22 Tishrei Israel')
T.eq(HC.getHoliday(5786, 7, 22, false).key, 'shemini_atzeret', '22 Tishrei diaspora')
T.eq(HC.getHoliday(5786, 7, 23, true), nil, '23 Tishrei Israel')
T.eq(HC.getHoliday(5786, 7, 23, false).key, 'simchat_torah', '23 Tishrei diaspora')
T.eq(HC.getHoliday(5786, 1, 22, true), nil, '22 Nisan Israel')
T.eq(HC.getHoliday(5786, 3, 6).key, 'shavuot_1', 'Shavuot')
T.eq(HC.getHoliday(5786, 3, 7, true), nil, '7 Sivan Israel')
T.eq(HC.getHoliday(5786, 3, 7, false).key, 'shavuot_2', '7 Sivan diaspora')
T.eq(HC.getHoliday(5786, 7, 9), nil, 'not holiday')

-- wrappers
local isH, name = HC.isHolidayThatReplacesTorah(5786, 'תשרי', 10)
T.eq(isH, true, 'YK wrapper'); T.eq(name, 'יום כיפור', 'YK name')
T.eq((HC.isHolidayThatReplacesTorah(5786, 'תשרי', 23)), false, '23 Tishrei default Israel')
T.eq((HC.isHolidayThatReplacesTorah(5786, 'תשרי', 23, false)), true, '23 Tishrei diaspora')
T.eq(HC.getHolidayReading('יום כיפור').maftir, 'במדבר כט, ז–יא', 'reading by name')
T.eq(HC.getHolidayReading('shavuot_2').haftarah, 'חבקוק ב, כ – ג, יט', 'reading by key')
T.eq(HC.getHolidayReading('ראש השנה').torah, 'בראשית כא, א–לד', 'legacy name')
T.eq(HC.getHolidayReading('nope'), nil, 'unknown reading')
local a = HC.checkHolidayOnSaturday(2025, 10, 11)
T.eq(a, true, 'checkHolidayOnSaturday')
T.eq((HC.checkHolidayOnSaturday(2025, 10, 7)), false, 'not saturday')
local b, n2, r2, info = HC.checkHolidayAnyDay(2025, 10, 2)
T.eq(b, true, 'YK any day'); T.eq(n2, 'יום כיפור', 'YK any name'); T.ok(r2 and info, 'reading+info')
